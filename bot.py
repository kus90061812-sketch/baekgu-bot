def automatic_enabled() -> bool:
    with engine.begin() as conn:
        row = conn.execute(
            text("SELECT value FROM settings WHERE key = :key"),
            {"key": "enabled"},
        ).fetchone()

    return bool(row and row[0] == "1")


def set_automatic(enabled: bool):
    value = "1" if enabled else "0"

    with engine.begin() as conn:
        row = conn.execute(
            text("SELECT key FROM settings WHERE key = :key"),
            {"key": "enabled"},
        ).fetchone()

        if row:
            conn.execute(
                text("""
                    UPDATE settings
                    SET value = :value
                    WHERE key = :key
                """),
                {"value": value, "key": "enabled"},
            )
        else:
            conn.execute(
                text("""
                    INSERT INTO settings(key, value)
                    VALUES(:key, :value)
                """),
                {"key": "enabled", "value": value},
            )


async def copy_with_retry(bot, group_id, source_chat, message_id, post_id):
    max_attempts = 3

    for attempt in range(1, max_attempts + 1):
        try:
            await bot.copy_message(
                chat_id=group_id,
                from_chat_id=source_chat,
                message_id=message_id,
            )
            log_send(group_id, post_id, "success")
            return True

        except RetryAfter as e:
            wait_for = retry_seconds(e.retry_after) + RETRY_EXTRA_SECONDS

            logger.warning(
                "429 RetryAfter | group=%s post=%s attempt=%s wait=%.1fs",
                group_id, post_id, attempt, wait_for
            )

            if attempt >= max_attempts:
                log_send(
                    group_id,
                    post_id,
                    "failed",
                    f"RetryAfter after {attempt} attempts",
                )
                return False

            await asyncio.sleep(wait_for)

        except Forbidden as e:
            log_send(group_id, post_id, "failed", f"Forbidden: {e}")
            return False

        except BadRequest as e:
            log_send(group_id, post_id, "failed", f"BadRequest: {e}")
            return False

        except TelegramError as e:
            if attempt >= max_attempts:
                log_send(group_id, post_id, "failed", f"TelegramError: {e}")
                return False
            await asyncio.sleep(3.0 * attempt)

        except Exception as e:
            logger.exception("Unknown error")
            log_send(group_id, post_id, "failed", f"Unknown: {e}")
            return False

    return False


async def send_all(application: Application):
    if SEND_LOCK.locked():
        return {"sent": 0, "failed": 0, "skipped": True}

    async with SEND_LOCK:
        with engine.begin() as conn:
            groups = conn.execute(
                text("""
                    SELECT chat_id, title
                    FROM target_groups
                    WHERE enabled = 1
                    ORDER BY added_at ASC
                """)
            ).mappings().all()

            posts = conn.execute(
                text("""
                    SELECT id, source_chat, message_id, original_link
                    FROM source_posts
                    WHERE enabled = 1
                    ORDER BY id ASC
                """)
            ).mappings().all()

        if not groups or not posts:
            return {"sent": 0, "failed": 0, "skipped": False}

        sent = 0
        failed = 0

        for group in groups:
            for post in posts:
                source_chat = post["source_chat"]

                if source_chat.lstrip("-").isdigit():
                    source_chat = int(source_chat)

                ok = await copy_with_retry(
                    application.bot,
                    group["chat_id"],
                    source_chat,
                    post["message_id"],
                    post["id"],
                )

                if ok:
                    sent += 1
                else:
                    failed += 1

                await asyncio.sleep(
                    random.uniform(MIN_SEND_DELAY, MAX_SEND_DELAY)
                )

        return {"sent": sent, "failed": failed, "skipped": False}


async def hourly_job(context: ContextTypes.DEFAULT_TYPE):
    if not automatic_enabled():
        return

    result = await send_all(context.application)
    logger.info("자동 발송 결과: %s", result)


async def cmd_send_now(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not await admin_guard(update):
        return

    if SEND_LOCK.locked():
        await update.effective_message.reply_text(
            "⏳ 이미 발송이 진행 중입니다."
        )
        return

    await update.effective_message.reply_text("📤 전체 발송 시작...")

    result = await send_all(context.application)

    await update.effective_message.reply_text(
        f"✅ 발송 완료\n"
        f"성공: {result['sent']}건\n"
        f"실패: {result['failed']}건"
    )


async def cmd_auto_start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not await admin_guard(update):
        return

    set_automatic(True)
    await update.effective_message.reply_text("✅ 자동 발송을 켰습니다.")


async def cmd_auto_stop(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not await admin_guard(update):
        return

    set_automatic(False)
    await update.effective_message.reply_text("⏸ 자동 발송을 중지했습니다.")


async def cmd_status(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not await admin_guard(update):
        return

    with engine.begin() as conn:
        group_count = conn.execute(
            text("""
                SELECT COUNT(*)
                FROM target_groups
                WHERE enabled = 1
            """)
        ).scalar_one()

        post_count = conn.execute(
            text("""
                SELECT COUNT(*)
                FROM source_posts
                WHERE enabled = 1
            """)
        ).scalar_one()

    state = "켜짐" if automatic_enabled() else "꺼짐"

    await update.effective_message.reply_text(
        f"🤖 현재 상태\n"
        f"DB: {DB_KIND}\n"
        f"자동 발송: {state}\n"
        f"주기: {SEND_INTERVAL_SECONDS // 60}분\n"
        f"등록 그룹: {group_count}개\n"
        f"등록 게시물: {post_count}개\n"
        f"발송 간격: {MIN_SEND_DELAY:.1f}~{MAX_SEND_DELAY:.1f}초"
    )


async def cmd_recent_logs(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not await admin_guard(update):
        return

    with engine.begin() as conn:
        rows = conn.execute(
            text("""
                SELECT group_id, post_id, status, error_text, created_at
                FROM send_logs
                ORDER BY id DESC
                LIMIT 20
            """)
        ).mappings().all()

    if not rows:
        await update.effective_message.reply_text("아직 발송 로그가 없습니다.")
        return

    lines = ["🧾 최근 발송 로그"]
    for row in rows:
        icon = "✅" if row["status"] == "success" else "❌"
        error = f" | {row['error_text']}" if row["error_text"] else ""
        lines.append(
            f"{icon} G:{row['group_id']} / P:{row['post_id']} "
            f"/ {row['created_at']}{error}"
        )

    text_out = "\n".join(lines)
    if len(text_out) > 3900:
        text_out = text_out[:3900] + "\n..."

    await update.effective_message.reply_text(text_out)


async def post_init(application: Application):
    init_db()

    application.job_queue.run_repeating(
        hourly_job,
        interval=SEND_INTERVAL_SECONDS,
        first=SEND_INTERVAL_SECONDS,
        name="hourly-relay",
    )

    logger.info("봇 시작 | DB=%s", DB_KIND)


def main():
    if not ADMIN_IDS:
        raise RuntimeError("ADMIN_IDS 환경변수를 설정해주세요.")

    app = (
        ApplicationBuilder()
        .token(TOKEN)
        .post_init(post_init)
        .build()
    )

    app.add_handler(CommandHandler(["start", "도움말"], cmd_help))

    app.add_handler(CommandHandler("등록", cmd_add_post))
    app.add_handler(CommandHandler("삭제", cmd_remove_post))
    app.add_handler(CommandHandler("등록목록", cmd_post_list))

    app.add_handler(CommandHandler("방등록", cmd_add_group))
    app.add_handler(CommandHandler("방삭제", cmd_remove_group))
    app.add_handler(CommandHandler("방목록", cmd_group_list))

    app.add_handler(CommandHandler("즉시발송", cmd_send_now))
    app.add_handler(CommandHandler("자동시작", cmd_auto_start))
    app.add_handler(CommandHandler("자동중지", cmd_auto_stop))
    app.add_handler(CommandHandler("상태", cmd_status))
    app.add_handler(CommandHandler("최근로그", cmd_recent_logs))

    app.run_polling(drop_pending_updates=False)


if __name__ == "__main__":
    main()
