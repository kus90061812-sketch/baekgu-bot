TOKEN = os.environ["BOT_TOKEN"]

ADMIN_IDS = {
    int(x.strip())
    for x in os.environ.get("ADMIN_IDS", "").split(",")
    if x.strip().isdigit()
}

DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
SQLITE_PATH = os.environ.get("DB_PATH", "relay_bot.db")

SEND_INTERVAL_SECONDS = int(os.environ.get("SEND_INTERVAL_SECONDS", "3600"))
MIN_SEND_DELAY = float(os.environ.get("MIN_SEND_DELAY", "1.2"))
MAX_SEND_DELAY = float(os.environ.get("MAX_SEND_DELAY", "2.0"))
RETRY_EXTRA_SECONDS = float(os.environ.get("RETRY_EXTRA_SECONDS", "1.0"))

logging.basicConfig(
    format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    level=logging.INFO,
)
logger = logging.getLogger("relay-bot")

SEND_LOCK = asyncio.Lock()

# Railway/Render PostgreSQL이 있으면 그걸 우선 사용.
# 없으면 로컬 SQLite로 자동 fallback.
if DATABASE_URL:
    # 일부 서비스가 postgres:// 형식을 줄 수 있어 SQLAlchemy 호환형으로 보정
    if DATABASE_URL.startswith("postgres://"):
        DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql+psycopg://", 1)
    elif DATABASE_URL.startswith("postgresql://"):
        DATABASE_URL = DATABASE_URL.replace("postgresql://", "postgresql+psycopg://", 1)

    engine = create_engine(
        DATABASE_URL,
        pool_pre_ping=True,
        pool_recycle=300,
    )
    DB_KIND = "PostgreSQL"
else:
    engine = create_engine(
        f"sqlite:///{SQLITE_PATH}",
        connect_args={"check_same_thread": False},
    )
    DB_KIND = "SQLite"


def init_db():
    with engine.begin() as conn:
        conn.execute(text("""
            CREATE TABLE IF NOT EXISTS target_groups (
                chat_id BIGINT PRIMARY KEY,
                title TEXT,
                added_at TEXT NOT NULL,
                enabled INTEGER NOT NULL DEFAULT 1
            )
        """))

        conn.execute(text("""
            CREATE TABLE IF NOT EXISTS source_posts (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source_chat TEXT NOT NULL,
                message_id BIGINT NOT NULL,
                original_link TEXT NOT NULL UNIQUE,
                added_at TEXT NOT NULL,
                enabled INTEGER NOT NULL DEFAULT 1
            )
        """) if DB_KIND == "PostgreSQL" else text("""
            CREATE TABLE IF NOT EXISTS source_posts (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                source_chat TEXT NOT NULL,
                message_id INTEGER NOT NULL,
                original_link TEXT NOT NULL UNIQUE,
                added_at TEXT NOT NULL,
                enabled INTEGER NOT NULL DEFAULT 1
            )
        """))

        conn.execute(text("""
            CREATE TABLE IF NOT EXISTS settings (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL
            )
        """))

        conn.execute(text("""
            CREATE TABLE IF NOT EXISTS send_logs (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                group_id BIGINT,
                post_id BIGINT,
                status TEXT NOT NULL,
                error_text TEXT,
                created_at TEXT NOT NULL
            )
        """) if DB_KIND == "PostgreSQL" else text("""
            CREATE TABLE IF NOT EXISTS send_logs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                group_id INTEGER,
                post_id INTEGER,
                status TEXT NOT NULL,
                error_text TEXT,
                created_at TEXT NOT NULL
            )
        """))

        existing = conn.execute(
            text("SELECT value FROM settings WHERE key = :key"),
            {"key": "enabled"},
        ).fetchone()

        if not existing:
            conn.execute(
                text("INSERT INTO settings(key, value) VALUES(:key, :value)"),
                {"key": "enabled", "value": "1"},
            )


def is_admin(update: Update) -> bool:
    user = update.effective_user
    return bool(user and user.id in ADMIN_IDS)


async def admin_guard(update: Update) -> bool:
    if is_admin(update):
        return True
    if update.effective_message:
        await update.effective_message.reply_text("관리자만 사용할 수 있습니다.")
    return False


def parse_telegram_post_link(link: str):
    link = link.strip()

    m = re.match(
        r"^https?://(?:t\.me|telegram\.me)/c/(\d+)/(\d+)(?:\?.*)?$",
        link,
        re.IGNORECASE,
    )
    if m:
        return int("-100" + m.group(1)), int(m.group(2))

    m = re.match(
        r"^https?://(?:t\.me|telegram\.me)/([A-Za-z0-9_]+)/(\d+)(?:\?.*)?$",
        link,
        re.IGNORECASE,
    )
    if m:
        return f"@{m.group(1)}", int(m.group(2))

    raise ValueError("지원하지 않는 텔레그램 게시물 링크입니다.")


def retry_seconds(value) -> float:
    if isinstance(value, timedelta):
        return max(value.total_seconds(), 1.0)
    try:
        return max(float(value), 1.0)
    except Exception:
        return 5.0


def log_send(group_id, post_id, status, error_text=None):
    try:
        with engine.begin() as conn:
            conn.execute(
                text("""
                    INSERT INTO send_logs(
                        group_id, post_id, status, error_text, created_at
                    )
                    VALUES(
                        :group_id, :post_id, :status, :error_text, :created_at
                    )
                """),
                {
                    "group_id": group_id,
                    "post_id": post_id,
                    "status": status,
                    "error_text": error_text,
                    "created_at": datetime.now().isoformat(timespec="seconds"),
                },
            )
    except Exception:
        logger.exception("발송 로그 저장 실패")


